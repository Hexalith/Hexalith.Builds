namespace Hexalith.Builds.Tooling.Workspace;

using System.Security;
using System.Text.Json.Nodes;

using Hexalith.Builds.Tooling.Runtime;

using Microsoft.Build.Evaluation;

/// <summary>Reproduces only SDK-originated locked-restore imports in private scratch.</summary>
internal static class RestoredBuildImportContract
{
    /// <summary>Verifies generated imports against an independent locked SDK restore.</summary>
    /// <param name="project">The isolated evaluated child.</param>
    /// <param name="properties">Its already authenticated closed property set.</param>
    /// <param name="builds">The actual active catalog root.</param>
    /// <param name="root">The authenticated module root.</param>
    /// <param name="tracked">The verified source/import inventory.</param>
    /// <returns>The exact two verified generated import paths.</returns>
    /// <exception cref="InvalidDataException">The SDK graph or generated bytes differ.</exception>
    internal static HashSet<string> Verify(Project project, IReadOnlyDictionary<string, string> properties, string builds, string root, IReadOnlySet<string> tracked)
    {
        string extensions = project.GetPropertyValue("MSBuildProjectExtensionsPath");
        string directoryProps = project.GetPropertyValue("DirectoryBuildPropsPath");
        string lockFile = project.GetPropertyValue("NuGetLockFilePath");
        if (!Path.IsPathRooted(extensions) || !File.Exists(directoryProps) || !File.Exists(lockFile)
            || !tracked.Contains(Path.GetRelativePath(root, directoryProps).Replace('\\', '/'))
            || !tracked.Contains(Path.GetRelativePath(root, lockFile).Replace('\\', '/'))
            || !Path.GetFullPath(extensions).StartsWith(project.DirectoryPath + Path.DirectorySeparatorChar, StringComparison.Ordinal))
        {
            throw new InvalidDataException("Isolated generated imports require explicit existing project extensions, source props and successor lock.");
        }

        for (DirectoryInfo? parent = new(extensions); parent is not null; parent = parent.Parent)
        {
            if ((parent.Attributes & FileAttributes.ReparsePoint) != 0)
            {
                throw new InvalidDataException("Restored project extensions traverse a symbolic link.");
            }
        }

        string sdk = project.GetPropertyValue("MSBuildToolsPath");
        if (!Path.IsPathRooted(sdk))
        {
            throw new InvalidDataException("The executing SDK import root is unavailable.");
        }

        string[] files = [project.Xml.FullPath + ".nuget.g.props", project.Xml.FullPath + ".nuget.g.targets"];
        string[] actual = [.. files.Select(path => Path.Combine(extensions, Path.GetFileName(path)))];
        foreach (ResolvedImport import in project.Imports.Where(import => actual.Contains(import.ImportedProject.FullPath, StringComparer.Ordinal)))
        {
            string origin = Path.GetRelativePath(sdk, import.ImportingElement.ContainingProject.FullPath);
            if (Path.IsPathRooted(origin) || origin == ".." || origin.StartsWith(".." + Path.DirectorySeparatorChar, StringComparison.Ordinal))
            {
                throw new InvalidDataException("Generated NuGet imports must originate in the executing SDK, not authored module imports.");
            }
        }

        string temporary = Path.Combine(Path.GetTempPath(), "hexalith-restore-witness-" + Guid.NewGuid().ToString("N"));
        CompositionWorkspace.CreatePrivateDirectory(temporary);
        try
        {
            string witnessProps = Path.Combine(temporary, "Witness.props");
            string output = Path.Combine(temporary, "projects") + Path.DirectorySeparatorChar;
            string xml = "<Project><Import Project=\"" + SecurityElement.Escape(directoryProps) + "\"/><PropertyGroup>"
                + "<BaseIntermediateOutputPath>" + SecurityElement.Escape(output) + "$(MSBuildProjectName)/obj/</BaseIntermediateOutputPath>"
                + "<MSBuildProjectExtensionsPath>$(BaseIntermediateOutputPath)</MSBuildProjectExtensionsPath></PropertyGroup></Project>";
            File.WriteAllText(witnessProps, xml);
            List<string> arguments = ["msbuild", project.Xml.FullPath, "-target:Restore", "-noAutoResponse", "-nodeReuse:false", "-maxcpucount:1", "-nologo", "-verbosity:quiet", "-warnaserror:NU1900;NU1903;NU1904;NU1905"];
            arguments.AddRange(properties.Select(pair => "-property:" + pair.Key + "=" + pair.Value));
            arguments.AddRange([
                "-property:DirectoryBuildPropsPath=" + witnessProps,
                "-property:RestoreConfigFile=" + Path.Combine(builds, "NuGet.ci.Config"),
                "-property:NuGetAudit=true",
                "-property:NuGetAuditMode=all",
                "-property:NuGetAuditLevel=low",
            ]);
            Dictionary<string, string> environment = new(StringComparer.Ordinal)
            {
                ["MSBUILDDISABLENODEREUSE"] = "1",
                ["DOTNET_CLI_USE_MSBUILD_SERVER"] = "0",
            };
            foreach (string name in new[] { "CustomBeforeDirectoryBuildProps", "CustomAfterMicrosoftCommonProps", "CustomBeforeDirectoryBuildTargets", "CustomAfterDirectoryBuildTargets", "AfterMicrosoftNETSdkTargets" })
            {
                environment[name] = string.Empty;
            }

#pragma warning disable VSTHRD002 // ITask.Execute is synchronous; bounded isolated SDK verification captures no context.
            CompositionProcessResult result = CompositionProcess.RunAsync(
                CompositionProcess.CreateStartInfo("dotnet", arguments, project.DirectoryPath, environment),
                TimeSpan.FromMinutes(2),
                CancellationToken.None).GetAwaiter().GetResult();
#pragma warning restore VSTHRD002
            if (!result.Started || result.TimedOut || result.OutputTruncated || result.ExitCode != 0)
            {
                throw new InvalidDataException("Independent locked restore refused isolated imports: " + result.Output + result.ErrorOutput);
            }

            string witness = Path.Combine(temporary, "projects", project.GetPropertyValue("MSBuildProjectName"), "obj");
            foreach (string file in actual)
            {
                string independentlyGenerated = Path.Combine(witness, Path.GetFileName(file));
                if (!File.Exists(file) || !File.Exists(independentlyGenerated)
                    || !File.ReadAllBytes(file).AsSpan().SequenceEqual(File.ReadAllBytes(independentlyGenerated)))
                {
                    throw new InvalidDataException("Generated NuGet import bytes differ from independent locked restore: " + Path.GetFileName(file));
                }
            }

            foreach (string section in new[] { "targets", "libraries" })
            {
                JsonNode restored = JsonNode.Parse(File.ReadAllBytes(Path.Combine(extensions, "project.assets.json")))!;
                JsonNode independentlyRestored = JsonNode.Parse(File.ReadAllBytes(Path.Combine(witness, "project.assets.json")))!;
                if (!JsonNode.DeepEquals(restored[section], independentlyRestored[section]))
                {
                    throw new InvalidDataException("Isolated restored assets graph differs from independent locked restore.");
                }
            }

            return actual.ToHashSet(StringComparer.Ordinal);
        }
        finally
        {
            Directory.Delete(temporary, recursive: true);
        }
    }
}
